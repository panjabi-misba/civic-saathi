export function signalCount(clusters: HeatmapCluster[]): Record<HeatmapSignal, number> {
  return {
    garbage: clusters.filter((c) => c.signal === 'garbage').length,
    streetlight: clusters.filter((c) => c.signal === 'streetlight').length,
    pothole: clusters.filter((c) => c.signal === 'pothole').length,
    water: clusters.filter((c) => c.signal === 'water').length,
  }
}

export function totalReports(clusters: HeatmapCluster[]): number {
  return clusters.reduce((sum, c) => sum + c.reports, 0)
}

export function totalNeighbours(clusters: HeatmapCluster[]): number {
  return clusters.reduce((sum, c) => sum + c.neighbours, 0)
}
